import { SerializerOptions, ExportResult } from '../types';
import { getExportTarget } from '../registry';

export function serializeToCss(options: SerializerOptions): ExportResult {
  const { normalized, style } = options;
  const target = getExportTarget('css');

  const groups = [
    { title: 'Base Canvas & Surfaces', category: 'color' as const, filter: (k: string) => ['background', 'surface', 'surfaceElevated', 'foreground', 'muted', 'mutedForeground'].includes(k) },
    { title: 'Brand Actions & Accents', category: 'color' as const, filter: (k: string) => ['primary', 'primaryHover', 'primaryForeground', 'secondary', 'secondaryForeground', 'accent', 'accentForeground'].includes(k) },
    { title: 'Borders & Focus Rings', category: 'color' as const, filter: (k: string) => ['border', 'borderSubtle', 'borderStrong', 'ring'].includes(k) },
    { title: 'Semantic Status', category: 'color' as const, filter: (k: string) => ['success', 'warning', 'destructive'].includes(k) },
    { title: 'Typography - Font Families', category: 'fontFamily' as const },
    { title: 'Typography - Font Sizes', category: 'fontSize' as const },
    { title: 'Typography - Font Weights', category: 'fontWeight' as const },
    { title: 'Typography - Line Heights & Letter Spacing', category: 'lineHeight' as const, includeLetterSpacing: true },
    { title: 'Spacing & Layout Rhythm', category: 'spacing' as const },
    { title: 'Geometry & Border Radii', category: 'borderRadius' as const },
    { title: 'Border Thicknesses', category: 'borderWidth' as const },
    { title: 'Shadows & Elevation', category: 'shadow' as const },
    { title: 'Motion & Interactive Transitions', category: 'transition' as const },
  ];

  let body = '';

  for (const group of groups) {
    let tokens = normalized.byCategory[group.category] || [];
    if (group.filter) {
      tokens = tokens.filter((t) => group.filter(t.key));
    }
    if (group.includeLetterSpacing) {
      tokens = [...tokens, ...(normalized.byCategory.letterSpacing || [])];
    }

    if (tokens.length > 0) {
      body += `\n  /* --- ${group.title} --- */\n`;
      for (const t of tokens) {
        body += `  ${t.cssVarName}: ${t.value};\n`;
      }
    }
  }

  const code = `/**
 * StyPro Design Tokens — ${normalized.styleName}
 * Architecture: CSS Custom Properties
 * Mode: ${normalized.isCustomized ? 'Customized Derivative System' : 'Canonical Style Standard'}
 * Generated by StyPro (From Style to Prompt to Code)
 * 
 * Usage:
 * Link this file or import into your global stylesheet:
 *   @import './${target.defaultFilename(style.slug)}';
 */

:root {${body}}

/* ==========================================================================
   Example Component Usage:
   ==========================================================================
   .sty-card {
     background-color: var(--sty-color-surface);
     color: var(--sty-color-foreground);
     padding: var(--sty-padding-content);
     border-radius: var(--sty-radius-md);
     border: var(--sty-border-width-thin) solid var(--sty-color-border);
     box-shadow: var(--sty-shadow-md);
   }

   .sty-button-primary {
     background-color: var(--sty-color-primary);
     color: var(--sty-color-primary-foreground);
     padding: 0.625rem 1.25rem;
     border-radius: var(--sty-radius-sm);
     font-family: var(--sty-font-heading);
     font-weight: var(--sty-font-weight-medium);
     transition: var(--sty-transition-default);
   }
   ========================================================================== */
`;

  return {
    format: 'css',
    code,
    filename: target.defaultFilename(style.slug),
    mimeType: target.mimeType,
  };
}

